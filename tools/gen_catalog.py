"""Write the browser's catalog lists from the Python catalog, which is their single source.

``consilith_room.protocols.a2ui`` names every component, variant and cap. The browser mirrors
them in ``apps/web/src/shared/a2ui/types.ts``, between the BEGIN and END GENERATED lines. This
script rewrites that region (formatted the way Biome formats it), and ``--check`` fails when the
file differs from what the catalog would produce, so a name added in Python cannot be forgotten
in the web app.

    uv run python tools/gen_catalog.py            # rewrite types.ts
    uv run python tools/gen_catalog.py --check    # exit 1 when types.ts is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "apps" / "web" / "src" / "shared" / "a2ui" / "types.ts"
BEGIN = "// BEGIN GENERATED by tools/gen_catalog.py from consilith_room.protocols.a2ui"
END = "// END GENERATED"
LINE_WIDTH = 100


def _array(name: str, values: list[str], *, typed: str = "") -> list[str]:
    """``export const NAME = [...] as const;`` on one line when it fits, else one per line."""
    head = f"export const {name}{typed} = "
    items = ", ".join(f'"{v}"' for v in values)
    one = f"{head}[{items}] as const;"
    if len(one) <= LINE_WIDTH:
        return [one]
    return [f"{head}[", *(f'  "{v}",' for v in values), "] as const;"]


def render(manifest: dict[str, Any]) -> str:
    """The generated region, without the markers' surroundings."""
    lines = [BEGIN + ": do not edit by hand."]
    lines.append(f'export const CATALOG_ID = "{manifest["catalogId"]}";')
    lines.append(f"export const MAX_COMPONENTS = {manifest['maxComponents']};")
    lines.append(f"export const MAX_DEPTH = {manifest['maxDepth']};")
    lines.append("")
    for name, key in (
        ("PANELS", "panels"),
        ("DATA_VIEWS", "dataViews"),
        ("TEXT_VARIANTS", "textVariants"),
        ("LAYOUT_KINDS", "layoutKinds"),
        ("LAYOUT_RATIOS", "layoutRatios"),
        ("LAYOUT_EMPHASES", "layoutEmphases"),
        ("LAYOUT_DENSITIES", "layoutDensities"),
    ):
        lines += _array(name, list(manifest[key]))
    lines.append("/** The variants a data view honours; any other value is refused. */")
    lines.append("export const VARIANTS: Readonly<Record<string, readonly string[]>> = {")
    for view, values in manifest["variants"].items():
        items = ", ".join(f'"{v}"' for v in values)
        lines.append(f"  {view}: [{items}],")
    lines.append("};")
    lines.append(END)
    return "\n".join(lines)


def splice(source: str, generated: str) -> str:
    """``source`` with the region between the markers replaced by ``generated``."""
    start = source.index(BEGIN)
    stop = source.index(END, start) + len(END)
    return source[:start] + generated + source[stop:]


def current() -> dict[str, Any]:
    from consilith_room.protocols import a2ui

    return a2ui.catalog_manifest()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the file is out of date")
    parser.add_argument("--target", type=Path, default=TARGET)
    args = parser.parse_args(argv)
    source = args.target.read_text(encoding="utf-8")
    wanted = splice(source, render(current()))
    if args.check:
        if wanted != source:
            print(f"{args.target} is out of date: run tools/gen_catalog.py", file=sys.stderr)
            return 1
        print("catalog lists are up to date")
        return 0
    if wanted != source:
        args.target.write_text(wanted, encoding="utf-8", newline="\n")
        print(f"wrote {args.target}")
    else:
        print("already up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
